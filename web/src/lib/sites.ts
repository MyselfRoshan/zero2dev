import { joinPath } from "./installer";
import type { Service, Settings, SiteServer } from "./types";

/** The program that serves the sites; settings from older daemons have no field, which means Caddy. */
export function siteServer(s: Pick<Settings, "siteServer"> | null | undefined): SiteServer {
  return s?.siteServer === "nginx" ? "nginx" : "caddy";
}

export const serverLabel = (s: SiteServer): string => (s === "nginx" ? "nginx" : "Caddy");

/** The managed nginx service for sites is recognised by its generated config argument. */
export const NGINX_CONF_ARG = "{home}/config/nginx.conf";

/** Whether svc is the service that serves the sites for the given server. */
export function isSiteServerService(svc: Pick<Service, "kind" | "args">, server: SiteServer): boolean {
  if (server === "nginx") return svc.kind === "nginx" && (svc.args ?? []).includes(NGINX_CONF_ARG);
  return svc.kind === "caddy";
}

/** Root certificate to trust for HTTPS sites served by nginx (generated by Zero2Dev). */
export function nginxCaPath(homeDir: string): string {
  return joinPath(homeDir, "nginx", "certs", "ca.crt");
}
