package kinds

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// Extension is a PHP extension found in a runtime's ext folder.
type Extension struct {
	Name string `json:"name"` // curl, pdo_mysql, xdebug ...
	File string `json:"file"` // php_curl.dll
	Zend bool   `json:"zend"` // loaded with zend_extension=
}

// zendExtensions are loaded with zend_extension= instead of extension=.
var zendExtensions = map[string]bool{"opcache": true, "xdebug": true}

// ExtDir is the ext folder next to a PHP binary.
func ExtDir(phpBin string) string { return filepath.Join(filepath.Dir(phpBin), "ext") }

// ListExtensions lists the extensions in the ext folder next to phpBin
// (php_<name>.dll on Windows, <name>.so elsewhere), sorted by name.
func ListExtensions(phpBin string) []Extension {
	ents, err := os.ReadDir(ExtDir(phpBin))
	if err != nil {
		return []Extension{}
	}
	out := []Extension{}
	for _, e := range ents {
		n := e.Name()
		if e.IsDir() {
			continue
		}
		var name string
		switch {
		case strings.HasPrefix(strings.ToLower(n), "php_") && strings.EqualFold(filepath.Ext(n), ".dll"):
			name = strings.ToLower(n[4 : len(n)-4])
		case strings.HasSuffix(n, ".so"):
			name = strings.TrimSuffix(n, ".so")
		default:
			continue
		}
		out = append(out, Extension{Name: name, File: n, Zend: zendExtensions[name]})
	}
	slices.SortFunc(out, func(a, b Extension) int { return strings.Compare(a.Name, b.Name) })
	return out
}

// PHPIniPath is where the php.ini of a PHP service is written.
func PHPIniPath(data string) string { return filepath.Join(data, "php.ini") }

// phpPlan adds the generated php.ini and its folders to pl.
func phpPlan(pl *Plan, eff map[string]string, ini [][2]string, c Ctx) {
	var b strings.Builder
	nl := "\n"
	if c.Windows {
		nl = "\r\n"
	}
	w := func(s string) { b.WriteString(s + nl) }
	w("; Generated by Zero2Dev for service " + c.ServiceID + " on every start.")
	w("; Change the service settings in Zero2Dev instead of editing this file.")
	if base := eff["iniBase"]; base != "none" && c.Bin != "" {
		src := filepath.Join(filepath.Dir(c.Bin), "php.ini-"+base)
		if body, err := os.ReadFile(src); err == nil {
			w("; ---- " + filepath.Base(src) + " (from the PHP folder) ----")
			b.Write(body)
			w("")
		}
	}
	w("; ---- Zero2Dev settings ----")
	w("[PHP]")
	quote := func(p string) string { return `"` + p + `"` }
	tmp := filepath.Join(c.Data, "tmp")
	sessions := filepath.Join(c.Data, "sessions")
	pl.Dirs = append(pl.Dirs, c.Data, tmp, sessions)
	have, hasExt := []Extension{}, false
	if c.Bin != "" {
		if _, err := os.Stat(ExtDir(c.Bin)); err == nil {
			w("extension_dir = " + quote(ExtDir(c.Bin)))
			have, hasExt = ListExtensions(c.Bin), true
		}
	}
	w("session.save_path = " + quote(sessions))
	w("upload_tmp_dir = " + quote(tmp))
	w("sys_temp_dir = " + quote(tmp))
	for _, kv := range ini {
		w(kv[0] + " = " + kv[1])
	}
	wanted := SplitList(eff["extensions"])
	for _, name := range wanted {
		i := slices.IndexFunc(have, func(e Extension) bool { return e.Name == name })
		if i < 0 {
			if name == "opcache" { // built in since PHP 8.5
				w("opcache.enable = 1")
				w("opcache.enable_cli = 1")
				continue
			}
			if hasExt { // without an ext folder (a system PHP) the extensions are not Zero2Dev's to manage
				pl.Warnings = append(pl.Warnings, "PHP extension "+name+" is not in "+ExtDir(c.Bin)+"; left out")
			}
			continue
		}
		e := have[i]
		if e.Zend {
			w("zend_extension = " + e.File)
		} else {
			w("extension = " + e.File)
		}
		switch name {
		case "opcache":
			w("opcache.enable = 1")
			w("opcache.enable_cli = 1")
		case "xdebug":
			out := filepath.Join(c.Data, "xdebug")
			pl.Dirs = append(pl.Dirs, out)
			w("xdebug.output_dir = " + quote(out))
		}
	}
	if extra := strings.TrimSpace(eff["iniLines"]); extra != "" {
		w("; ---- More lines from the service settings ----")
		for _, l := range strings.Split(strings.ReplaceAll(extra, "\r\n", "\n"), "\n") {
			w(strings.TrimSpace(l))
		}
	}
	pl.Files = append(pl.Files, File{Path: PHPIniPath(c.Data), Content: []byte(b.String())})
}
