type fakeSup struct {
	mu        sync.Mutex
	state     string
	restarted []string
}

func (f *fakeSup) State(string) string { f.mu.Lock(); defer f.mu.Unlock(); return f.state }
func (f *fakeSup) setState(s string)   { f.mu.Lock(); f.state = s; f.mu.Unlock() }
func (f *fakeSup) count() int          { f.mu.Lock(); defer f.mu.Unlock(); return len(f.restarted) }
func (f *fakeSup) Restart(id string) error {
	f.mu.Lock()
	f.restarted = append(f.restarted, id)
	f.mu.Unlock()
	return nil
}

func TestCaddyfileGolden(t *testing.T) {
	d := store.Data{
		Settings: model.Settings{ProxyHTTPPort: 8080, ProxyHTTPSPort: 8443, DomainSuffix: "localhost"},
		Services: []model.Service{{ID: "svc_1", Port: 3000}, {ID: "svc_2", Port: 0}},
		Sites: []model.Site{
			{ID: "s1", Domain: "shop.localhost", Type: "proxy", ServiceID: "svc_1", Enabled: true},
			{ID: "s2", Domain: "docs.localhost", Type: "static", Root: "/srv/my docs", HTTPS: true, Enabled: true},
			{ID: "s3", Domain: "off.localhost", Type: "proxy", UpstreamPort: 9000, Enabled: false},
			{ID: "s4", Domain: "api.localhost", Type: "proxy", UpstreamPort: 4000, Enabled: true},
			{ID: "s5", Domain: "broken.localhost", Type: "proxy", ServiceID: "svc_2", Enabled: true},
			{ID: "s6", Domain: "plain.localhost", Type: "static", Root: "/srv/plain", Enabled: true},
		},
	}
	want := `# Generated by Zero2Dev. Do not edit; changes are overwritten.
{
	http_port 8080
	https_port 8443
	auto_https disable_redirects
}

http://api.localhost:8080 {
	reverse_proxy 127.0.0.1:4000
}

docs.localhost {
	tls internal
	root * "/srv/my docs"
	file_server
}

http://plain.localhost:8080 {
	root * /srv/plain
	file_server
}

http://shop.localhost:8080 {
	reverse_proxy 127.0.0.1:3000
}
`
	if got := Caddyfile(d); got != want {
		t.Fatalf("Caddyfile mismatch.\n--- got ---\n%s\n--- want ---\n%s", got, want)
	}
}

