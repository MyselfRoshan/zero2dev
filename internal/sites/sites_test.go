func TestCreateValidateAndWriteFile(t *testing.T) {
	m, st, sup, home := newMgr(t)
	root := t.TempDir()
	st.Update(func(d *store.Data) error {
		d.Services = append(d.Services, model.Service{ID: "svc_1", Name: "api", Kind: "node", Port: 3000}, model.Service{ID: "svc_p", Name: "web", Kind: "php", Port: 8000}, model.Service{ID: "svc_np", Name: "np", Kind: "custom"})
		d.Services = append(d.Services, model.Service{ID: "svc_c", Name: "Caddy", Kind: "caddy"})
		return nil
	})
	sup.setState("running")

	v, err := m.Create(model.SiteInput{Name: "Shop", Domain: " Shop.LocalHost ", Type: "proxy", ServiceID: "svc_1"})
	if err != nil {
		t.Fatal(err)
	}
	if v.Domain != "shop.localhost" || !v.Enabled || v.URL != "http://shop.localhost:8080" || !strings.HasPrefix(v.ID, "site_") {
		t.Fatalf("%+v", v)
	}
	b, _ := os.ReadFile(filepath.Join(home, "config", "Caddyfile"))
	if !strings.Contains(string(b), "reverse_proxy 127.0.0.1:3000") {
		t.Fatalf("Caddyfile not written:\n%s", b)
	}
	// running caddy service is restarted (async)
	for i := 0; i < 200 && sup.count() == 0; i++ {
		time.Sleep(10 * time.Millisecond)
	}
	if sup.count() == 0 {
		t.Fatal("running caddy service was not restarted")
	}

	v2, err := m.Create(model.SiteInput{Name: "Docs", Domain: "docs.test", Type: "static", Root: root, HTTPS: true})
	if err != nil || v2.URL != "https://docs.test:8443" {
		t.Fatalf("%+v %v", v2, err)
	}

	bad := []struct {
		name string
		in   model.SiteInput
	}{
		{"dup domain", model.SiteInput{Name: "x", Domain: "shop.localhost", Type: "proxy", UpstreamPort: 1}},
		{"bad suffix", model.SiteInput{Name: "x", Domain: "shop.example.com", Type: "proxy", UpstreamPort: 1}},
		{"newline injection", model.SiteInput{Name: "x", Domain: "a.localhost\n{ respond \"x\" }", Type: "proxy", UpstreamPort: 1}},
		{"no name", model.SiteInput{Domain: "n.localhost", Type: "proxy", UpstreamPort: 1}},
		{"static needs root", model.SiteInput{Name: "x", Domain: "r.localhost", Type: "static"}},
		{"relative root", model.SiteInput{Name: "x", Domain: "r.localhost", Type: "static", Root: "rel"}},
		{"missing root", model.SiteInput{Name: "x", Domain: "r.localhost", Type: "static", Root: root + "/nope"}},
		{"root with brace", model.SiteInput{Name: "x", Domain: "r.localhost", Type: "static", Root: "/tmp/{env.HOME}"}},
		{"proxy needs target", model.SiteInput{Name: "x", Domain: "r.localhost", Type: "proxy"}},
		{"unknown service", model.SiteInput{Name: "x", Domain: "r.localhost", Type: "proxy", ServiceID: "svc_zz"}},
		{"service no port", model.SiteInput{Name: "x", Domain: "r.localhost", Type: "proxy", ServiceID: "svc_np"}},
		{"php wrong kind", model.SiteInput{Name: "x", Domain: "r.localhost", Type: "php", ServiceID: "svc_1"}},
		{"bad type", model.SiteInput{Name: "x", Domain: "r.localhost", Type: "ftp"}},
	}
	for _, c := range bad {
		if _, err := m.Create(c.in); err == nil {
			t.Errorf("%s: expected error", c.name)
		}
	}
	if n := len(m.List()); n != 2 {
		t.Fatalf("failed creates must not persist, have %d", n)
	}

	// php + update + delete
	off := false
	up, err := m.Update(v.ID, model.SiteInput{Name: "Shop", Domain: "shop.localhost", Type: "php", ServiceID: "svc_p", Enabled: &off})
	if err != nil || up.Enabled || up.Type != "php" {
		t.Fatalf("%+v %v", up, err)
	}
	b, _ = os.ReadFile(filepath.Join(home, "config", "Caddyfile"))
	if strings.Contains(string(b), "shop.localhost") {
		t.Fatal("disabled site must not appear")
	}
	if _, err := m.Update("site_none", model.SiteInput{}); err == nil {
		t.Fatal("update of unknown id")
	}
	if err := m.Delete(v.ID); err != nil {
		t.Fatal(err)
	}
	if err := m.Delete(v.ID); err == nil {
		t.Fatal("double delete")
	}
}

func TestEnsureCaddy(t *testing.T) {
	m, st, _, home := newMgr(t)
	if c, _ := m.EnsureCaddy(); c {
		t.Fatal("no runtime, no service")
	}
	st.Update(func(d *store.Data) error {
		d.Runtimes = append(d.Runtimes, model.Runtime{ID: "rt_1", Kind: "caddy", Binary: "/x/caddy"})
		return nil
	})
	if c, err := m.EnsureCaddy(); !c || err != nil {
		t.Fatalf("should create: %v %v", c, err)
	}
	if c, _ := m.EnsureCaddy(); c {
		t.Fatal("must not create twice")
	}
	svcs := st.Snapshot().Services
	if len(svcs) != 1 || svcs[0].Name != "Caddy" || svcs[0].Kind != "caddy" || svcs[0].Port != 0 || svcs[0].Cwd != home {
		t.Fatalf("%+v", svcs)
	}
	if _, err := os.Stat(filepath.Join(home, "config", "Caddyfile")); err != nil {
		t.Fatal("Caddyfile must exist")
	}
}
