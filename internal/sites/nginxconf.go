// Site servers: which program serves the sites (setting siteServer).
const (
	ServerCaddy = "caddy"
	ServerNginx = "nginx"
)

// Server returns the configured site server; empty (state files written
// before the setting existed) means Caddy.
func Server(st model.Settings) string {
	if st.SiteServer == ServerNginx {
		return ServerNginx
	}
	return ServerCaddy
}

// NginxArgs are the arguments of the managed "Nginx (sites)" service. The
// supervisor replaces {home} with the data folder at start, so the service
// keeps working when the folder is moved.
var NginxArgs = []string{"-p", "{home}/nginx/", "-c", "{home}/config/nginx.conf"}

// IsSitesNginx reports whether svc is the managed nginx service that serves
// the sites (as opposed to a user's own nginx service with its own config).
func IsSitesNginx(svc model.Service) bool {
	if svc.Kind != "nginx" {
		return false
	}
	for _, a := range svc.Args {
		if a == "{home}/config/nginx.conf" {
			return true
		}
	}
	return false
}

// nginxPaths are the absolute, slash-separated paths the config refers to.
type nginxPaths struct {
	cert, key string
}

func pathsFor(home string) nginxPaths {
	dir := filepath.ToSlash(filepath.Join(home, "nginx", "certs"))
	return nginxPaths{cert: dir + "/sites.crt", key: dir + "/sites.key"}
}

// NginxConf renders nginx.conf for the given state. Like Caddyfile it is
// deterministic and only interpolates validated values (hostname regex,
// ints, roots without quotes, braces, '$', backslashes or control chars).
// Relative paths (pid, temp folders) resolve against the -p prefix
// <home>/nginx/.
func NginxConf(d store.Data, home string) string {
	d = withoutBroken(d)
	st := d.Settings
	p := pathsFor(home)
	var b strings.Builder
	b.WriteString("# Generated by Zero2Dev. Do not edit; changes are overwritten.\n")
	b.WriteString("daemon off;\n")
	b.WriteString("worker_processes 1;\n")
	b.WriteString("error_log stderr notice;\n")
	b.WriteString("pid logs/nginx.pid;\n\n")
	b.WriteString("events {\n\tworker_connections 1024;\n}\n\n")
	b.WriteString("http {\n")
	b.WriteString(mimeTypes)
	b.WriteString("\tdefault_type application/octet-stream;\n")
	b.WriteString("\taccess_log off;\n")
	b.WriteString("\tsendfile on;\n")
	b.WriteString("\tclient_max_body_size 0;\n")
	b.WriteString("\tserver_names_hash_bucket_size 128;\n")
	b.WriteString("\tmap $http_upgrade $connection_upgrade {\n\t\tdefault upgrade;\n\t\t'' close;\n\t}\n")

	sites := append([]model.Site{}, d.Sites...)
	sort.Slice(sites, func(i, j int) bool { return sites[i].Domain < sites[j].Domain })
	svcPort := map[string]int{}
	for _, s := range d.Services {
		svcPort[s.ID] = s.Port
	}
	anyTLS := false
	for _, s := range sites {
		if s.Enabled && s.HTTPS {
			anyTLS = true
		}
	}

	// Unknown hosts get 404 instead of the first site.
	fmt.Fprintf(&b, "\n\tserver {\n\t\tlisten 127.0.0.1:%d default_server;\n\t\tserver_name _;\n\t\treturn 404;\n\t}\n", st.ProxyHTTPPort)
	if anyTLS {
		fmt.Fprintf(&b, "\n\tserver {\n\t\tlisten 127.0.0.1:%d ssl default_server;\n\t\tserver_name _;\n%s\t\treturn 404;\n\t}\n", st.ProxyHTTPSPort, tlsLines(p))
	}

	for _, s := range sites {
		if !s.Enabled {
			continue
		}
		b.WriteString("\n\tserver {\n")
		if s.HTTPS {
			fmt.Fprintf(&b, "\t\tlisten 127.0.0.1:%d ssl;\n", st.ProxyHTTPSPort)
		} else {
			fmt.Fprintf(&b, "\t\tlisten 127.0.0.1:%d;\n", st.ProxyHTTPPort)
		}
		fmt.Fprintf(&b, "\t\tserver_name %s;\n", s.Domain)
		if s.HTTPS {
			b.WriteString(tlsLines(p))
		}
		switch s.Type {
		case "static":
			fmt.Fprintf(&b, "\t\troot \"%s\";\n\t\tindex index.html index.htm;\n", filepath.ToSlash(s.Root))
			b.WriteString("\t\tlocation / {\n\t\t\ttry_files $uri $uri/ =404;\n\t\t}\n")
		default: // proxy, php
			port := s.UpstreamPort
			if s.ServiceID != "" {
				port = svcPort[s.ServiceID]
			}
			fmt.Fprintf(&b, "\t\tlocation / {\n\t\t\tproxy_pass http://127.0.0.1:%d;\n", port)
			b.WriteString("\t\t\tproxy_http_version 1.1;\n")
			b.WriteString("\t\t\tproxy_set_header Host $host;\n")
			b.WriteString("\t\t\tproxy_set_header X-Real-IP $remote_addr;\n")
			b.WriteString("\t\t\tproxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n")
			b.WriteString("\t\t\tproxy_set_header X-Forwarded-Proto $scheme;\n")
			b.WriteString("\t\t\tproxy_set_header Upgrade $http_upgrade;\n")
			b.WriteString("\t\t\tproxy_set_header Connection $connection_upgrade;\n")
			b.WriteString("\t\t}\n")
		}
		b.WriteString("\t}\n")
	}
	b.WriteString("}\n")
	return b.String()
}

func tlsLines(p nginxPaths) string {
	return fmt.Sprintf("\t\tssl_certificate \"%s\";\n\t\tssl_certificate_key \"%s\";\n", p.cert, p.key)
}

// httpsDomains lists the enabled HTTPS sites that the generated config
// serves, sorted: the names the certificate must cover.
func httpsDomains(d store.Data) []string {
	var out []string
	for _, s := range withoutBroken(d).Sites {
		if s.Enabled && s.HTTPS {
			out = append(out, s.Domain)
		}
	}
	sort.Strings(out)
	return out
}

// unsafeForNginx: inside a quoted nginx string '$' starts a variable and a
// backslash is an escape. Checked on the slash form of the root.
func unsafeForNginx(p string) bool {
	return strings.ContainsAny(filepath.ToSlash(p), `$\`)
}

