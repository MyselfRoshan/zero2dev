package sites

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"zero2dev/internal/model"
	"zero2dev/internal/store"
)

// Caddyfile renders the full Caddyfile for the given state. The output is
// deterministic (sites sorted by domain). Every interpolated value was
// validated beforehand (strict hostname regex, ints, paths without quotes,
// braces or control characters), so no value can inject Caddyfile syntax.
func Caddyfile(d store.Data) string {
	d = withoutBroken(d)
	var b strings.Builder
	b.WriteString("# Generated by Zero2Dev. Do not edit; changes are overwritten.\n")
	b.WriteString("{\n")
	fmt.Fprintf(&b, "\thttp_port %d\n", d.Settings.ProxyHTTPPort)
	fmt.Fprintf(&b, "\thttps_port %d\n", d.Settings.ProxyHTTPSPort)
	b.WriteString("\tauto_https disable_redirects\n}\n")

	sites := append([]model.Site{}, d.Sites...)
	sort.Slice(sites, func(i, j int) bool { return sites[i].Domain < sites[j].Domain })
	svcPort := map[string]int{}
	for _, s := range d.Services {
		svcPort[s.ID] = s.Port
	}
	for _, s := range sites {
		if !s.Enabled {
			continue
		}
		fmt.Fprintf(&b, "\n%s {\n", address(s, d.Settings))
		if s.HTTPS {
			b.WriteString("\ttls internal\n")
		}
		switch s.Type {
		case "static":
			fmt.Fprintf(&b, "\troot * %s\n\tfile_server\n", quotePath(s.Root))
		default: // proxy, php
			port := s.UpstreamPort
			if s.ServiceID != "" {
				port = svcPort[s.ServiceID]
			}
			fmt.Fprintf(&b, "\treverse_proxy 127.0.0.1:%d\n", port)
		}
		b.WriteString("}\n")
	}
	return b.String()
}

// withoutBroken disables proxy sites whose service vanished or has no port,
// so one stale site cannot break the whole Caddyfile.
func withoutBroken(d store.Data) store.Data {
	svcPort := map[string]int{}
	for _, s := range d.Services {
		svcPort[s.ID] = s.Port
	}
	out := d
	out.Sites = nil
	for _, s := range d.Sites {
		if s.Enabled && s.Type != "static" {
			port := s.UpstreamPort
			if s.ServiceID != "" {
				port = svcPort[s.ServiceID]
			}
			if port <= 0 {
				s.Enabled = false
			}
		}
		out.Sites = append(out.Sites, s)
	}
	return out
}

// address is the site address line: http://<domain>:<httpPort> or, for
// https sites, the bare domain (Caddy serves it on https_port with its
// internal CA).
func address(s model.Site, st model.Settings) string {
	if s.HTTPS {
		return s.Domain
	}
	return "http://" + s.Domain + ":" + strconv.Itoa(st.ProxyHTTPPort)
}

// URL is the browser URL for a site.
func URL(s model.Site, st model.Settings) string {
	if s.HTTPS {
		return "https://" + s.Domain + ":" + strconv.Itoa(st.ProxyHTTPSPort)
	}
	return "http://" + s.Domain + ":" + strconv.Itoa(st.ProxyHTTPPort)
}

func quotePath(p string) string {
	if strings.ContainsAny(p, " \t") {
		return `"` + p + `"`
	}
	return p
}
