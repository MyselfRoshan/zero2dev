func byName(files []File) map[string]string {
	m := map[string]string{}
	for _, f := range files {
		m[f.Name] = f.Content
	}
	return m
}

func TestShimCmdGolden(t *testing.T) {
	got := ShimCmd(`C:\z\bin\node\node.exe`, nil)
	want := "@echo off\r\nrem Generated by Zero2Dev. Do not edit: it is rewritten when the runtimes change.\r\n\"C:\\z\\bin\\node\\node.exe\" %*\r\n"
	if got != want {
		t.Fatalf("got %q", got)
	}
	got = ShimCmd(`C:\z\jdk\bin\java.exe`, map[string]string{"JAVA_HOME": `C:\z\jdk`})
	want = "@echo off\r\nrem Generated by Zero2Dev. Do not edit: it is rewritten when the runtimes change.\r\nsetlocal\r\nset \"JAVA_HOME=C:\\z\\jdk\"\r\n\"C:\\z\\jdk\\bin\\java.exe\" %*\r\n"
	if got != want {
		t.Fatalf("got %q", got)
	}
}

func TestShimCmdQuotingOfSpecialCharacters(t *testing.T) {
	got := ShimCmd(`C:\100%\a & b ^ (c)\node.exe`, map[string]string{"GOROOT": `C:\100%\go&`})
	for _, want := range []string{
		`"C:\100%%\a & b ^ (c)\node.exe" %*`, // % doubled, the rest inert inside the quotes
		`set "GOROOT=C:\100%%\go&"`,
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("missing %q in %q", want, got)
		}
	}
}

func TestActivateScriptsGolden(t *testing.T) {
	dirs := []string{`C:\z\bin\node`, `C:\z\jdk\bin`}
	env := map[string]string{"JAVA_HOME": `C:\z\jdk`, "GOROOT": `C:\z\it's\go`}
	cmd := ActivateCmd(dirs, env)
	for _, want := range []string{
		"set \"PATH=C:\\z\\bin\\node;C:\\z\\jdk\\bin;%PATH%\"\r\n",
		"set \"GOROOT=C:\\z\\it's\\go\"\r\nset \"JAVA_HOME=C:\\z\\jdk\"\r\n", // sorted
	} {
		if !strings.Contains(cmd, want) {
			t.Fatalf("activate.cmd lacks %q: %q", want, cmd)
		}
	}
	ps := ActivatePS1(dirs, env)
	for _, want := range []string{
		"$env:PATH = 'C:\\z\\bin\\node;C:\\z\\jdk\\bin;' + $env:PATH\r\n",
		"$env:GOROOT = 'C:\\z\\it''s\\go'\r\n", // ' doubled
		"$env:JAVA_HOME = 'C:\\z\\jdk'\r\n",
	} {
		if !strings.Contains(ps, want) {
			t.Fatalf("activate.ps1 lacks %q: %q", want, ps)
		}
	}
	sh := ActivateSH(dirs, env)
	if strings.Contains(sh, "\r") {
		t.Fatal("activate.sh must use LF")
	}
	i1 := strings.Index(sh, `__z2d_path 'C:\z\bin\node'`)
	i2 := strings.Index(sh, `__z2d_path 'C:\z\jdk\bin'`)
	if i1 < 0 || i2 < 0 || i2 > i1 {
		t.Fatalf("the first dir must be prepended last so it ends up first: %q", sh)
	}
	if !strings.Contains(sh, `export GOROOT="$(__z2d_path 'C:\z\it'\''s\go')"`) {
		t.Fatalf("sh quoting: %q", sh)
	}
	if got := psQuote("a‘b"); got != "'a‘‘b'" {
		t.Fatalf("typographic quote not doubled: %q", got)
	}
}

func TestFilesForTheDefaultRuntimes(t *testing.T) {
	z := filepath.Join("z", "bin")
	node1 := filepath.Join(z, "node-1", "node.exe")
	node2 := filepath.Join(z, "node-2", "node.exe")
	java := filepath.Join(z, "jdk", "bin", "java.exe")
	goBin := filepath.Join(z, "go", "bin", "go.exe")
	pg := filepath.Join(z, "pg", "bin", "postgres.exe")
	d := store.Data{Runtimes: []model.Runtime{
		{Kind: "node", Binary: node1},
		{Kind: "node", Binary: node2, Default: true},
		{Kind: "java", Binary: java, Default: true},
		{Kind: "go", Binary: goBin},
		{Kind: "postgres", Binary: pg},
		{Kind: "caddy", Binary: filepath.Join(z, "caddy.exe")},
	}}
	present := map[string]bool{
		filepath.Join(z, "node-2", "npm.cmd"):       true, // a .cmd beside node.exe
		filepath.Join(z, "node-2", "npx.cmd"):       true,
		filepath.Join(z, "node-1", "npm.cmd"):       true, // not the default: ignored
		filepath.Join(z, "jdk", "bin", "javac.exe"): true,
		filepath.Join(z, "pg", "bin", "psql.exe"):   true,
	}
	files := Files(d, func(p string) bool { return present[p] })
	got := byName(files)
	for _, name := range []string{"node.cmd", "npm.cmd", "npx.cmd", "java.cmd", "javac.cmd", "go.cmd", "psql.cmd", "activate.cmd", "activate.ps1", "activate.sh"} {
		if _, ok := got[name]; !ok {
			t.Errorf("%s missing; have %v", name, names(files))
		}
	}
	for _, name := range []string{"gofmt.cmd", "jar.cmd", "pg_dump.cmd", "php.cmd", "caddy.cmd", "postgres.cmd"} {
		if _, ok := got[name]; ok {
			t.Errorf("%s must not be generated", name)
		}
	}
	if got["node.cmd"] != ShimCmd(node2, nil) {
		t.Errorf("node.cmd targets the wrong runtime: %q", got["node.cmd"])
	}
	if got["npm.cmd"] != ShimCmd(filepath.Join(z, "node-2", "npm.cmd"), nil) {
		t.Errorf("npm.cmd = %q", got["npm.cmd"])
	}
	if got["java.cmd"] != ShimCmd(java, map[string]string{"JAVA_HOME": filepath.Join(z, "jdk")}) ||
		got["javac.cmd"] != ShimCmd(filepath.Join(z, "jdk", "bin", "javac.exe"), map[string]string{"JAVA_HOME": filepath.Join(z, "jdk")}) {
		t.Errorf("java shims set JAVA_HOME: %q", got["java.cmd"])
	}
	if got["go.cmd"] != ShimCmd(goBin, map[string]string{"GOROOT": filepath.Join(z, "go")}) {
		t.Errorf("go.cmd = %q", got["go.cmd"])
	}
	// The activate scripts list the default runtimes' folders in kind order.
	wantPath := strings.Join([]string{filepath.Join(z, "node-2"), filepath.Join(z, "jdk", "bin"), filepath.Join(z, "go", "bin"), filepath.Join(z, "pg", "bin")}, ";")
	if !strings.Contains(got["activate.cmd"], `set "PATH=`+wantPath+`;%PATH%"`) {
		t.Errorf("activate.cmd = %q", got["activate.cmd"])
	}
	for _, f := range files {
		if !strings.Contains(f.Content, marker) {
			t.Errorf("%s has no marker", f.Name)
		}
	}
}

func TestFilesMysqlWinsOverMariadbForTheSameCommand(t *testing.T) {
	z := filepath.Join("z", "bin")
	d := store.Data{Runtimes: []model.Runtime{
		{Kind: "mariadb", Binary: filepath.Join(z, "maria", "bin", "mariadbd.exe"), Default: true},
		{Kind: "mysql", Binary: filepath.Join(z, "my", "bin", "mysqld.exe"), Default: true},
	}}
	all := func(string) bool { return true }
	got := byName(Files(d, all))
	if got["mysql.cmd"] != ShimCmd(filepath.Join(z, "my", "bin", "mysql.exe"), nil) {
		t.Errorf("mysql.cmd = %q", got["mysql.cmd"])
	}
	if got["mariadb.cmd"] == "" {
		t.Error("mariadb.cmd missing")
	}
}

func TestFilesWithoutRuntimesStillHaveActivateScripts(t *testing.T) {
	files := Files(store.Data{}, func(string) bool { return true })
	if len(files) != 3 {
		t.Fatalf("files = %v", names(files))
	}
}

func names(fs []File) []string {
	out := make([]string, len(fs))
	for i, f := range fs {
		out[i] = f.Name
	}
	return out
}
